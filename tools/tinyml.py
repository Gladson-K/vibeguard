"""Post-training symmetric int8 quantization + C header export for TinyML."""
from __future__ import annotations

from pathlib import Path

import numpy as np

from tools.autoencoder import _act

ACT_CODE = {"linear": 0, "tanh": 1, "relu": 2}
ACT_NAME = {0: "linear", 1: "tanh", 2: "relu"}


def _scale(x: np.ndarray) -> float:
    m = float(np.max(np.abs(x))) if x.size else 0.0
    return m / 127.0 if m > 1e-12 else 1e-6


def quantize(model, X_calib: np.ndarray) -> list[dict]:
    """Return per-layer int8 weights + per-tensor scales (calibrated)."""
    layers = []
    in_scale = _scale(X_calib)
    a = X_calib
    for W, b, kind in zip(model.W, model.b, model.acts):
        w_scale = _scale(W)
        w_int8 = np.round(W / w_scale).astype(np.int32)
        out = _act(a @ W + b, kind)
        out_scale = _scale(out)
        layers.append(
            {
                "w_int8": w_int8.T.tolist(),  # (out, in)
                "w_scale": w_scale,
                "b": np.asarray(b, dtype=float).tolist(),
                "in_scale": in_scale,
                "out_scale": out_scale,
                "activation": ACT_NAME.get(kind, "linear"),
                "in_dim": int(W.shape[0]),
                "out_dim": int(W.shape[1]),
            }
        )
        a = out
        in_scale = out_scale
    return layers


def emulate_int8(layers: list[dict], X: np.ndarray) -> np.ndarray:
    """Reference int8 forward pass, matching firmware/src/vg_core/model.cpp."""
    q = np.clip(np.round(X / layers[0]["in_scale"]), -127, 127).astype(np.int64)
    cur = None
    for li, L in enumerate(layers):
        w = np.asarray(L["w_int8"], dtype=np.float64)  # (out, in)
        acc = q @ w.T
        y = acc * (L["w_scale"] * L["in_scale"]) + np.asarray(L["b"], dtype=float)
        y = _act(y, ACT_CODE[L["activation"]])
        if li + 1 < len(layers):
            q = np.clip(np.round(y / L["out_scale"]), -127, 127).astype(np.int64)
        cur = y
    return np.mean((X - cur) ** 2, axis=1)


def arena_bytes(layers: list[dict], in_dim: int) -> int:
    weights = sum(L["out_dim"] * L["in_dim"] for L in layers)
    biases = sum(L["out_dim"] for L in layers) * 4
    norm = in_dim * 4 * 2
    scratch = max([in_dim] + [L["out_dim"] for L in layers]) * (4 + 1)
    return int(weights + biases + norm + scratch)


def _ffmt(v, suffix="f"):
    s = f"{float(v):.8g}"
    if "." not in s and "e" not in s and "E" not in s:
        s += ".0"
    return s + suffix


def _farr(vals, cast="float", suffix="f"):
    if cast == "int8_t":
        body = ",".join(str(int(v)) for v in vals)
    else:
        body = ",".join(_ffmt(v, suffix) for v in vals)
    return body


def emit_header(path: str | Path, artifact: dict) -> None:
    layers = artifact["layers"]
    in_dim = artifact["in_dim"]
    lines = [
        "// AUTO-GENERATED by tools/train_autoencoder.py -- do not edit.",
        "#pragma once",
        '#include "model.h"',
        f"#define VG_MODEL_IN_DIM {in_dim}",
        f"#define VG_MODEL_N_LAYERS {len(layers)}",
        f"static const float VG_INPUT_MEAN[{in_dim}] = {{{_farr(artifact['input_mean'])}}};",
        f"static const float VG_INPUT_STD[{in_dim}] = {{{_farr(artifact['input_std'])}}};",
        f"static const float VG_THRESHOLD = {artifact['threshold']:.8g}f;",
    ]
    for i, L in enumerate(layers):
        w = [v for row in L["w_int8"] for v in row]
        lines.append(
            f"static const int8_t VG_W{i}[{len(w)}] = {{{_farr(w, cast='int8_t')}}};"
        )
        lines.append(f"static const float VG_WS{i} = {L['w_scale']:.8g}f;")
        lines.append(
            f"static const float VG_B{i}[{L['out_dim']}] = {{{_farr(L['b'])}}};"
        )
        lines.append(f"static const float VG_IS{i} = {L['in_scale']:.8g}f;")
        lines.append(f"static const float VG_OS{i} = {L['out_scale']:.8g}f;")
    lines.append(f"static const QLayer VG_LAYERS[{len(layers)}] = {{")
    for i, L in enumerate(layers):
        lines.append(
            f"  {{VG_W{i}, VG_B{i}, VG_WS{i}, VG_IS{i}, VG_OS{i}, "
            f"{L['in_dim']}, {L['out_dim']}, {ACT_CODE[L['activation']]}}},"
        )
    lines.append("};")
    lines.append(
        f'static const QModel VG_MODEL = {{VG_LAYERS, {len(layers)}, VG_INPUT_MEAN, '
        f'VG_INPUT_STD, {in_dim}, VG_THRESHOLD, "{artifact["version"]}"}};'
    )
    Path(path).write_text("\n".join(lines) + "\n")
